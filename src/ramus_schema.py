"""The fixed part of every Ramus 3 file - what the application's plugins put into a new file
before there is any model in it.

Ramus keeps a model in database tables and a .rsf is their dump, so a file carries, besides
the model: the catalogs (qualifiers) and attributes its plugins register, and a description of
its own tables - ``persistents`` (one per attribute table, with the class that reads it) and
``persistent_fields`` (their columns) - which the application reads to know how to load the
rest. None of it depends on the model. These are the values of the desktop Ramus 3 that the
owner's models come from; Ramus Next writes the same rows, apart from the Chart plugin it was
built without, and CLOB where Ramus writes CHAR in a few system columns.

Facts about the format, gathered from the files, as plain data; :mod:`blank_model` builds a
new file from them.
"""

